// countryAlias is one alias, matched longest first so "South Sudan" is not
// read as "Sudan" and "Papua New Guinea" not as "Guinea".
type countryAlias struct {
	code string
	re   *regexp.Regexp
	n    int
}

var (
	countryAliases []countryAlias
	marketNames    = map[string]string{}
)

func init() {
	for _, c := range countries {
		marketNames[c.code] = c.name
		for _, a := range c.aliases {
			re := regexp.MustCompile(`(?i)(?:^|[^\p{L}\p{N}])` + strings.ReplaceAll(regexp.QuoteMeta(a), " ", `\s+`) + `(?:$|[^\p{L}\p{N}])`)
			countryAliases = append(countryAliases, countryAlias{c.code, re, len(a)})
		}
	}
	sort.SliceStable(countryAliases, func(i, j int) bool { return countryAliases[i].n > countryAliases[j].n })
}

// MarketOf returns the ISO code of the country a message names, or "".
func MarketOf(text string) string {
	for _, a := range countryAliases {
		if a.re.MatchString(text) {
			return a.code
		}
	}
	return ""
}
