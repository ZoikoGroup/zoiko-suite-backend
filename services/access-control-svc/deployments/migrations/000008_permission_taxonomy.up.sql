-- Migration 000008: the permission taxonomy (Authorization Standard §5, §22).
--
-- permitted_actions used to be a free []string. Any spelling was accepted, so a
-- bundle could grant "payment.relase" or "PAYMNET_APPROVE": a grant nothing
-- enforces, a control in name only, which the register displayed as real.
-- §22 makes permission_definition an IAM Policy object ("stable protected
-- capabilities"), and this service is the IAM Policy authoring layer, so the
-- registry lives here and every bundle write is validated against it.
--
-- Two kinds of entry:
--
--   TAXONOMY  §5's namespaced `resource.action` names. The §9.1 archetype
--             templates (000009) and authorization-svc's §10.1 baseline are
--             written in these. The CHECK below holds their shape.
--   LEGACY    the SCREAMING_SNAKE names the estate enforces today, taken from
--             every action authorization-svc grants and every action constant
--             a service authorizes against (6 Oct 2026). Grandfathered so no
--             existing role breaks; new names should be TAXONOMY.
--
-- A new action is registered by migration, by the IAM Policy owner, never by a
-- tenant: a tenant that could register names could register a typo.

CREATE TABLE IF NOT EXISTS permission_definitions (
    action_name   VARCHAR(200) PRIMARY KEY,
    naming        VARCHAR(10)  NOT NULL CHECK (naming IN ('TAXONOMY', 'LEGACY')),
    risk_tier     VARCHAR(10)  NOT NULL DEFAULT 'STANDARD' CHECK (risk_tier IN ('STANDARD', 'HIGH', 'CRITICAL')),
    description   TEXT         NOT NULL DEFAULT '',
    active_flag   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- §5: "resource.action". Lower snake segments, at least two, so "admin"
    -- or "*" (a universal admin) cannot be registered as a taxonomy action.
    CONSTRAINT permission_definitions_taxonomy_shape CHECK (
        naming = 'LEGACY' OR action_name ~ '^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'
    ),
    CONSTRAINT permission_definitions_legacy_shape CHECK (
        naming = 'TAXONOMY' OR action_name ~ '^[A-Z][A-Z0-9]*(_[A-Z0-9]+)+$'
    )
);

-- Platform-wide, like protected_permissions: every tenant reads the same
-- registry, and nothing writes it through RLS.
ALTER TABLE permission_definitions ENABLE ROW LEVEL SECURITY;
ALTER TABLE permission_definitions FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS permission_definitions_read ON permission_definitions;
CREATE POLICY permission_definitions_read ON permission_definitions FOR SELECT USING (true);

